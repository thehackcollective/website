#!/usr/bin/env bash
set -euo pipefail

export CLERK_SECRET_KEY="${CLERK_DEV_SECRET_KEY:-}"
export CLERK_PUBLISHABLE_KEY="${CLERK_DEV_PUBLISHABLE_KEY:-}"
[[ -z "$CLERK_SECRET_KEY" ]] && unset CLERK_SECRET_KEY
[[ -z "$CLERK_PUBLISHABLE_KEY" ]] && unset CLERK_PUBLISHABLE_KEY
unset CLERK_DEV_SECRET_KEY CLERK_DEV_PUBLISHABLE_KEY CLERK_PROD_SECRET_KEY CLERK_PROD_PUBLISHABLE_KEY
exec "$@"
